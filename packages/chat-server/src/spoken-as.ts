function givenName(name: string): string {
  const first = name.trim().split(/\s+/)[0] ?? '';
  return first
    .normalize('NFD')
    .replace(/[\u0300-\u036f]/g, '')
    .toLowerCase();
}

export function spokenAs(name: string | null | undefined): 'he' | 'she' | null {
  if (!name?.trim()) return null;
  const given = givenName(name);
  if (!given) return null;
  const he = HE.has(given);
  const she = SHE.has(given);
  if (he === she) return null;
  return he ? 'he' : 'she';
}
